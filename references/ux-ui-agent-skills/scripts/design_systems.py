#!/usr/bin/env python3
"""Browse and apply the design-system library (design-systems/library/).

Usage:
  python3 scripts/design_systems.py list                 # all systems by category
  python3 scripts/design_systems.py search <term>        # name/description match
  python3 scripts/design_systems.py show <name>          # print a system's DESIGN.md path + summary
  python3 scripts/design_systems.py categories           # category counts
  python3 scripts/design_systems.py catalog              # design-systems/catalog.md, as markdown
  python3 scripts/design_systems.py index                # design-systems/library.json

An npm install carries the index and no spec, so list, search, categories and
show read the index; a spec is fetched with `node scripts/library.mjs get <name>`.
catalog and index are generated from the specs on disk, which only the repo has.
"""
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIB = ROOT / "design-systems" / "library"
INDEX = ROOT / "design-systems" / "library.json"


def scalar(lines, i):
    """The top-level YAML string value that starts on lines[i] (`key: ...`).

    Covers the four shapes the library uses - double-quoted, single-quoted,
    folded or literal block, and plain (which may continue on indented lines).
    Stdlib only, so the script runs anywhere python3 does. When the measured
    specs were imported, its category and description for all 2,087 of them
    matched a real YAML parser's; tests/unit/python_units.py pins each shape.
    """
    value = lines[i].split(":", 1)[1].strip()
    more = []
    for line in lines[i + 1:]:
        if line[:1] not in (" ", "\t") and line.strip():
            break
        more.append(line.strip())
    if value[:1] in (">", "|"):
        joiner = " " if value[0] == ">" else "\n"
        return joiner.join(m for m in more if m).strip()
    if value.startswith('"'):
        return json.loads(" ".join([value] + [m for m in more if m]))
    if value.startswith("'"):
        return " ".join([value] + [m for m in more if m])[1:-1].replace("''", "'")
    return " ".join([value] + [m for m in more if m]).strip()


def meta(p):
    """Return (category, description) from a DESIGN.md.

    Two shapes ship. A measured spec opens with YAML frontmatter that carries
    `category:` and `description:`; the hand-written ones open with a title,
    then `> Category: ...` and a one-line `> description`.
    """
    text = p.read_text(encoding="utf-8", errors="ignore")
    if text.startswith("---\n") and "\n---\n" in text[4:]:
        lines = text[4:text.index("\n---\n", 4)].split("\n")
        found = {}
        for i, line in enumerate(lines):
            key = line.split(":", 1)[0]
            if key in ("category", "description") and key not in found:
                found[key] = scalar(lines, i)
        return found.get("category", "Uncategorized"), found.get("description", "")
    cat, desc = "Uncategorized", ""
    for line in text.splitlines()[:12]:
        if line.startswith("> Category:"):
            cat = line.split(":", 1)[1].strip()
        elif line.startswith("> ") and "Category:" not in line and not desc:
            desc = line[2:].strip()
    return cat, desc


def title(p):
    """The system's display name: frontmatter `name:`, else the H1 without its
    "Design System Inspired by" prefix."""
    text = p.read_text(encoding="utf-8", errors="ignore")
    if text.startswith("---\n") and "\n---\n" in text[4:]:
        lines = text[4:text.index("\n---\n", 4)].split("\n")
        for i, line in enumerate(lines):
            if line.startswith("name:"):
                return scalar(lines, i)
    for line in text.splitlines():
        if line.startswith("# "):
            return re.sub(r"^Design System Inspired by\s+", "", line[2:].strip())
    return p.parent.name


def catalog(s):
    """design-systems/catalog.md. tests/meta/registry.test.mjs fails when the
    committed file differs from this, so it cannot drift from the folder."""
    by_cat = {}
    for slug, (f, cat, _) in s.items():
        by_cat.setdefault(cat, []).append((slug, title(f)))
    esc = lambda t: re.sub(r"([\\`*_\[\]<>|#])", r"\\\1", t)
    out = [
        "# Design-system catalog",
        "",
        "Generated by `python3 scripts/design_systems.py catalog > design-systems/catalog.md`.",
        "Do not edit by hand: `tests/meta/registry.test.mjs` fails when this file and",
        "`design-systems/library/` disagree.",
        "",
        "An npm install carries no spec until one is asked for:",
        "`node scripts/library.mjs get <name>` fetches it and checks its sha256.",
        "",
        f"**{len(s):,} systems in {len(by_cat)} categories.** To find one, searching is faster",
        "than reading: `python3 scripts/design_systems.py search <term>`, or the",
        "`get_design_system` MCP tool.",
        "",
    ]
    for cat in sorted(by_cat, key=str.lower):
        out += [f"## {cat} ({len(by_cat[cat])})", ""]
        out += [f"- [`{slug}`](library/{slug}/DESIGN.md) {esc(name)}" for slug, name in by_cat[cat]]
        out.append("")
    return "\n".join(out)


def scan():
    """Every spec on disk, read from the files themselves."""
    if not LIB.is_dir():
        return {}
    out = {}
    for d in sorted(LIB.iterdir()):
        f = d / "DESIGN.md"
        if f.is_file():
            out[d.name] = (f, *meta(f))
    return out


def repo_and_ref():
    pkg = json.loads((ROOT / "package.json").read_text(encoding="utf-8"))
    m = re.search(r"github\.com/([^/]+/[^/.]+)", pkg["repository"]["url"])
    return m.group(1), "v" + pkg["version"]


def index(s):
    """design-systems/library.json: what an install needs to find a spec and to
    trust it once fetched. scripts/library.mjs refuses any byte that does not hash
    to `sha256` here, and fetches from `repo` at `ref`, the tag this was made for.
    One system per line so a diff shows which specs changed."""
    repo, ref = repo_and_ref()
    rows = []
    for slug, (f, cat, desc) in s.items():
        data = f.read_bytes()
        row = {"name": title(f), "category": cat, "description": desc,
               "sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data)}
        rows.append(f"    {json.dumps(slug)}: {json.dumps(row, ensure_ascii=False)}")
    head = f'{{\n  "repo": {json.dumps(repo)},\n  "ref": {json.dumps(ref)},\n  "systems": {{\n'
    return head + ",\n".join(rows) + "\n  }\n}\n"


def systems():
    """slug -> (path, category, description). The index when there is one, so an
    install that holds two specs still knows about all of them; `path` may not
    exist yet. The repo's index is held to its folder by tests/meta/registry.test.mjs."""
    if not INDEX.is_file():
        return scan()
    data = json.loads(INDEX.read_text(encoding="utf-8"))
    return {slug: (LIB / slug / "DESIGN.md", row["category"], row["description"])
            for slug, row in data["systems"].items()}


def cmd_list(s):
    by_cat = {}
    for name, (_, cat, desc) in s.items():
        by_cat.setdefault(cat, []).append((name, desc))
    for cat in sorted(by_cat):
        print(f"\n{cat} ({len(by_cat[cat])})")
        for name, desc in by_cat[cat]:
            print(f"  {name:24} {desc[:60]}")


def cmd_search(s, term):
    t = term.lower()
    hits = [(n, d) for n, (_, c, d) in s.items() if t in n.lower() or t in d.lower() or t in c.lower()]
    if not hits:
        print(f"No match for {term!r}.")
        return
    for n, d in hits:
        print(f"  {n:24} {d[:60]}")


def cmd_show(s, name):
    if name not in s:
        print(f"Unknown system {name!r}. Try: search {name}")
        return 1
    f, cat, desc = s[name]
    print(f"{name}  [{cat}]\n{desc}\n")
    if f.is_file():
        print(f"Spec: {f}")
    else:
        print(f"Spec: not in this install yet. Fetch it: node scripts/library.mjs get {name}")
    print("Apply: read this DESIGN.md, then map values via design-systems/interop-protocol.md")
    return 0


def main(argv):
    if argv[:1] in (["catalog"], ["index"]):
        s = scan()
        if not s:
            print(f"No specs on disk at {LIB}; {argv[0]} is generated from them.", file=sys.stderr)
            return 1
        sys.stdout.write(catalog(s) if argv[0] == "catalog" else index(s))
        return 0
    s = systems()
    if not s:
        print(f"No library at {LIB}")
        return 1
    if not argv or argv[0] == "list":
        cmd_list(s)
    elif argv[0] == "categories":
        from collections import Counter
        c = Counter(cat for _, cat, _ in s.values())
        for cat, n in sorted(c.items()):
            print(f"  {n:3}  {cat}")
        print(f"\nTotal: {len(s)} systems")
    elif argv[0] == "search" and len(argv) > 1:
        cmd_search(s, argv[1])
    elif argv[0] == "show" and len(argv) > 1:
        return cmd_show(s, argv[1])
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    # Findings quote what they found (an arrow, an emoji, a Thai name), and a
    # Windows console in a legacy code page cannot print it.
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stderr.reconfigure(encoding="utf-8")
    sys.exit(main(sys.argv[1:]))
